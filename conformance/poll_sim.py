"""Reference simulator for the Poll Backoff Contract.

THE canonical source of expected poll counts (Poll Backoff Contract, v27,
2026-07-23): the expected-count table is generated by ``python poll_sim.py``,
and each SDK's unit tests assert their client's observed poll count EQUALS this
simulator's output for the same parameters — an independent implementation of
the contract, so the comparison is a real cross-check, not a tautology.

Counting model (normative):
- polls == GETs; the first GET is issued immediately (t=0, job creation
  excluded from the budget);
- each GET costs ``rtt_s`` (the full round trip). The server SNAPSHOTS the
  job's status when it PROCESSES the request — modeled at the GET's ISSUE
  time ``t`` — and the response then travels back, landing at ``t + rtt``
  (v20). A real backend fixes ``job.status`` before serializing and
  transmitting, so it CANNOT reflect a completion that happens while the
  response is in flight; the pre-v20 model snapshotted at landing (t + rtt),
  which optimistically credited the response leg to the job and flipped
  boundary cases (e.g. job_29.97s at rtt 80 ms) to success where a real
  server times them out. A job of duration D is therefore terminal on the
  first GET ISSUED at or after D (its response landing at D_issue + rtt);
- ``draw`` is the U(0,1) jitter draw: 0.5 = expected value, 0.0 = worst case
  (max polls);
- the wall-clock budget is checked before each GET; sleeps are bounded by the
  remaining budget;
- strict acceptance (v5+): the deadline is checked when the response LANDS
  (at t + rtt) and BEFORE the terminal check — a response landing at/after
  the deadline times out, even a terminal one, matching the SDK loops. So a
  GET whose snapshot saw the job terminal still times out if its response
  lands past the deadline (snapshot→acceptance ≤ rtt).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional, Sequence, Union

WARM_S = 1.5
RAMP_S = (0.1, 0.2, 0.4, 0.8, 1.0)
HARD_CAP_S = 5.0
HINT_MIN_MS = 50
HINT_MAX_MS = 5000
# Final-poll reserve (v10): a pending-path sleep that would otherwise reach
# the deadline is shortened so ONE last GET is ISSUED with the reserve
# remaining. The reserve guarantees the ISSUE, not the completion: the
# response is accepted only when it lands STRICTLY inside the budget, so the
# final GET succeeds iff its full round trip (network + body read + the
# loop's acceptance check) takes strictly LESS than the reserve — at exactly
# 100 ms the strict boundary rejects it (v12; pinned by the
# job_29.89s_plain_rtt_* canonical pair). Without the reserve, a hint
# comparable to the remaining budget turns a would-succeed job into a
# poll-timeout (e.g. a 29 s job with a 5 s hint and a 30 s budget). v14
# made the reserve STATEFUL (first natural inside-reserve landing polls
# immediately); v15 replaces the post-tail-poll "sleep to the deadline"
# with CALLER-PACED tail polling (min(interval, remaining)) — sleeping to
# the deadline forfeited round trips that still fit the budget whenever
# interval + rtt < remaining (a 2.914 s job under a 3 s budget timed out
# with 86 ms still on the clock). Together with both densification bounds
# this yields the UNIVERSAL WINDOW guarantee, for round trips strictly
# inside the reserve: any job completing at least
#     W = rtt + min(RESERVE, interval + rtt)
# before the deadline succeeds under ANY schedule, hinted or plain —
# property-swept over timeouts x intervals x rtts x hints x draws. Inside
# W the outcome is a landing-phase lottery; it is NOT symmetric near
# rtt == reserve (the hinted schedule's last useful GET is issued earlier
# on average), which the terminal-window scan pins with exact counts.
FINAL_POLL_RESERVE_S = 0.1

# A dynamic hint schedule for the wire: [t_from_s, hint_ms] steps — the hint
# at response time t is the value of the LAST step with t_from STRICTLY < t
# (the first step's value when none is). Transitions are EXCLUSIVE at the
# boundary (v13): the backend ladder keeps the old rung at exact equality
# (`raw_ms <= step`, poll_hint_service.to_ladder_ms), so at t exactly 16.0 s
# the age floor is still 2000 — an inclusive `t >= t_from` lookup diverged
# from the deployed formula at every rung boundary. This is the
# JSON-serializable form of a callable schedule, shared by the canonical
# cases and the SDK test harnesses (a callable can't live in poll_cases.json).
HintSchedule = Sequence[Sequence[float]]
HintSpec = Union[int, Callable[[float], Optional[int]], None]


def schedule_fn(schedule: HintSchedule) -> Callable[[float], Optional[int]]:
    def hint(t: float) -> Optional[int]:
        value = int(schedule[0][1])
        for t_from, ms in schedule:
            if t > t_from:
                value = int(ms)
        return value

    return hint


# A VARIABLE round-trip schedule (v18): [poll_from, rtt_ms] steps — the rtt
# for poll index i (1-based) is the value of the LAST step with poll_from
# STRICTLY < i (the first step's value when none is). The JSON-serializable
# form of a callable rtt (a callable can't live in poll_cases.json), used to
# replay a per-poll-varying round trip through the real SDK loops — a
# constant rtt models ZERO variance and can't exercise the max-vs-average
# distinction the window guarantee rests on.
def rtt_schedule_fn(schedule: HintSchedule) -> Callable[[int], float]:
    def rtt(i: int) -> float:
        value = float(schedule[0][1])
        for poll_from, ms in schedule:
            if i > poll_from:
                value = float(ms)
        return value / 1000.0

    return rtt


@dataclass
class SimResult:
    polls: int
    latency_s: float
    timed_out: bool


def simulate(
    job_s: float,
    *,
    interval_s: float = 0.05,
    rtt_s: Union[float, Callable[[int], float]] = 0.01,
    timeout_s: float = 30.0,
    draw: Union[float, Callable[[int], float]] = 0.5,
    hint_ms: HintSpec = None,
) -> SimResult:
    cap_eff = max(HARD_CAP_S, interval_s)
    t = 0.0
    polls = 0
    ramp_i = 0
    # Stateful final-poll reserve (v14): True once the reserve-preserved
    # final GET has been scheduled — either via a tail-shortened sleep or
    # via the immediate inside-reserve poll below.
    tail_poll_spent = False
    while True:
        if timeout_s - t <= 0:
            return SimResult(polls, t, True)
        polls += 1
        # The server snapshots job.status when it PROCESSES this GET —
        # modeled at ISSUE time (v20). It cannot report a completion that
        # happens while the response is travelling back.
        snapshot_t = t
        # rtt_s may be a callable(poll_index) -> float (v18): a VARIABLE
        # round trip. The universal-window guarantee needs an UPPER bound on
        # EVERY poll's rtt, not an average — a single latency spike on the
        # final guard poll can land it past the deadline. A constant rtt_s
        # models zero variance, so a callable is the only way to exercise
        # the spike (poll_index is 1-based: this poll's number).
        this_rtt = rtt_s(polls) if callable(rtt_s) else rtt_s
        t += this_rtt  # response lands
        if t >= timeout_s:
            # Strict acceptance boundary: landed at/after the deadline —
            # rejected even if the snapshot was terminal.
            return SimResult(polls, t, True)
        if snapshot_t >= job_s:
            # The server SAW the job terminal at snapshot time and the
            # response landed strictly inside the budget.
            return SimResult(polls, t, False)
        warm = t < WARM_S
        if warm:
            sleep = interval_s
        else:
            base = max(RAMP_S[ramp_i], interval_s)
            ramp_i = min(ramp_i + 1, len(RAMP_S) - 1)
            # hint_ms may be a callable(t) -> Optional[int]: a DYNAMIC hint
            # schedule (e.g. the backend's per-phase age floor). The server
            # computes BOTH the status and the hint in ONE response, at the
            # request-processing SNAPSHOT time — NOT at landing (v20 fixed
            # status at snapshot but left the hint at landing t, a two-slice
            # response no real route emits; v21 evaluates the hint at
            # ``snapshot_t`` too).
            hint_val = hint_ms(snapshot_t) if callable(hint_ms) else hint_ms
            if hint_val is not None and type(hint_val) is int and HINT_MIN_MS <= hint_val <= HINT_MAX_MS:
                target = min(max(base, hint_val / 1000.0), cap_eff)
            else:
                target = min(base, cap_eff)
            # Deadline-aware densification (v14): the target never exceeds
            # HALF the remaining budget (floored at the caller's interval),
            # so as the deadline nears the schedule geometrically approaches
            # the plain schedule's landing density — a sparse hinted tail
            # otherwise gambles away a job completing just inside the
            # budget on a single landing.
            target = min(target, max((timeout_s - t) / 2.0, interval_s))
            # Ramp-in bound (v15, symmetric to densification): the target
            # never exceeds HALF the job's own elapsed time either — a host
            # hint (max(host_rung, age_rung) with a slow host median) used
            # to jump a job straight from the warm phase into 5 s sleeps,
            # costing a 1.6 s job +4.4 s. The geometric ramp-in caps the
            # overhead at ~60 % of the job's own duration while converging
            # to the full hint within a few sleeps on genuinely long jobs.
            target = min(target, max(t / 2.0, interval_s))
            lo = max(0.8 * target, interval_s)
            hi = min(1.2 * target, cap_eff)
            # draw may be a callable(poll_index) -> float: an adversarial
            # JITTER SEQUENCE (v14) — a constant draw cannot hit corner
            # cases that need different jitter on different sleeps.
            d = draw(polls) if callable(draw) else draw
            sleep = lo if hi <= lo else lo + (hi - lo) * d
        # Bound with the final-poll reserve — mirrors PollPacer._bound.
        # v14 made the reserve STATEFUL: a pending response can LAND inside
        # the reserve window naturally (long hinted sleep + real RTT), and
        # v10-v13's "sleep runs to the deadline" branch then never issued
        # the final GET at all. The FIRST inside-reserve pending landing
        # polls again IMMEDIATELY (still time for a < remaining round
        # trip). v15: AFTER that tail poll, polling continues at the
        # CALLER'S OWN interval until the deadline instead of sleeping the
        # whole remainder — the caller-sanctioned density is not a burst,
        # and sleeping to the deadline forfeited round trips that still fit
        # whenever interval + rtt < remaining (the custom-timeout
        # counterexample: 2.914 s job, 3 s budget, timed out 86 ms early).
        remaining = timeout_s - t
        tail = max(0.0, remaining - FINAL_POLL_RESERVE_S)
        if sleep <= tail:
            t += sleep
        elif remaining > FINAL_POLL_RESERVE_S:
            tail_poll_spent = True
            t += tail
        elif not tail_poll_spent:
            tail_poll_spent = True  # immediate final GET: sleep 0
        else:
            t += min(interval_s, max(0.0, remaining))  # caller-paced tail (v15)


