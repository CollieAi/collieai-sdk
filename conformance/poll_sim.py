def canonical_cases() -> dict:
    cases = []
    for spec in CANONICAL_CASES:
        hint: HintSpec = spec["hint_ms"]
        if spec.get("hint_schedule") is not None:
            hint = schedule_fn(spec["hint_schedule"])
        rtt: Union[float, Callable[[int], float]] = spec.get("rtt_s", 0.01)
        if spec.get("rtt_schedule") is not None:
            rtt = rtt_schedule_fn(spec["rtt_schedule"])
        result = simulate(
            spec["job_s"],
            draw=spec["draw"],
            hint_ms=hint,
            rtt_s=rtt,
            timeout_s=spec.get("timeout_s", 30.0),
            interval_s=spec.get("interval_s", 0.05),
        )
        cases.append({**spec, "polls": result.polls, "timed_out": result.timed_out})
    return {"interval_s": 0.05, "rtt_s": 0.01, "timeout_s": 30.0, "cases": cases}


def _flat(job_s: float, interval_s: float = 0.05, rtt_s: float = 0.01, timeout_s: float = 30.0) -> SimResult:
    """Pre-amendment behavior for the comparison column."""
    t = 0.0
    polls = 0
    while True:
        polls += 1
        t += rtt_s
        if t >= job_s:
            return SimResult(polls, t, False)
        if t >= timeout_s:
            return SimResult(polls, t, True)
        t += interval_s


